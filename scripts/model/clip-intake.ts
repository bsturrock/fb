// Run-clip intake (plan 06): inventory and calibration record of the supplied clips in models/animations/. Reads the
// manifest, hashes the preserved originals and the derivatives, analyses the samples (src/sim/run-clip.ts: loop seam,
// root motion, lengths, stance intervals, in-place nominal speed) and compares the clip rest skeleton with the
// calibrated player. Output: src/sim/model/run-clips.record.json (tests/locomotion.test.ts checks it reproduces).
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { analyzeRunClip, RUN_CLIP_POLICY, RunClipError, type RunClipRecord, type RunClipSource } from '../../src/sim/run-clip';
import CAL from '../../src/sim/model/bew-v6.calibration.json';

const DIR = 'models/animations';
const sha = (path: string): string => createHash('sha256').update(readFileSync(path)).digest('hex');
const r6 = (x: number): number => Math.round(x * 1e6) / 1e6;

export interface ManifestEntry {
  id: string;
  source: string;
  sourceSha256: string;
  data: string;
  fps: number;
  frames: number;
  sampleSpanS: number;
  rootMotion: string;
  removedTravelM: [number, number, number];
  kind?: 'idle' | 'walk';
}

export interface RunClipsRecord {
  note: string;
  convention: Record<string, string>;
  policy: typeof RUN_CLIP_POLICY;
  calibrationSha256: string;
  clips: RunClipRecord[];
  /** Plan 08: the supplied walk cycle, analysed like a run clip and kept apart: the run profiles do not play it. */
  walk: RunClipRecord;
}

export function clipIntake(dir = DIR): RunClipsRecord {
  const manifest = JSON.parse(readFileSync(`${dir}/manifest.json`, 'utf8')) as ManifestEntry[];
  // plan 10b: the record needs exactly one walk cycle; say so by name rather than fail on a missing record later
  const walks = manifest.filter((m) => m.kind === 'walk');
  if (walks.length !== 1) throw new RunClipError('walk', `the manifest needs exactly one walk clip (kind 'walk'), it has ${walks.length}${walks.length ? `: ${walks.map((m) => m.id).join(', ')}` : ''}`);
  // the idle source has its own intake (scripts/model/idle-intake.ts): it is not a run clip
  const clips = manifest.filter((m) => m.kind !== 'idle').map((m) => {
    const isWalk = m.kind === 'walk';
    const srcPath = `${dir}/${m.source}`;
    const got = sha(srcPath);
    if (got !== m.sourceSha256) throw new RunClipError(m.id, `source ${m.source} sha256 ${got} differs from the manifest ${m.sourceSha256}`);
    const dataPath = `${dir}/${m.data}`;
    const raw = JSON.parse(readFileSync(dataPath, 'utf8')) as RunClipSource;
    const a = analyzeRunClip(m.id, raw);
    if (a.sourceFrames !== m.frames || a.fps !== m.fps) throw new RunClipError(m.id, `manifest frames/fps ${m.frames}/${m.fps} differ from the data ${a.sourceFrames}/${a.fps}`);
    // the clip rest skeleton against the calibrated player's rest joints (body-local = GLB world - origin)
    const o = CAL.frame.origin;
    let restVs = 0;
    for (const [j, p] of Object.entries(raw.rest)) {
      const c = (CAL.restJoints as Record<string, { p: number[] }>)[j];
      if (!c) continue;
      restVs = Math.max(restVs, Math.hypot(p[0] - o[0] - c.p[0], p[1] - o[1] - c.p[1], p[2] - o[2] - c.p[2]));
    }
    const rec: RunClipRecord = {
      id: m.id,
      name: raw.name,
      source: srcPath,
      sourceSha256: m.sourceSha256,
      data: dataPath,
      dataSha256: sha(dataPath),
      rootMotion: { policy: m.rootMotion, removedAtBakeM: m.removedTravelM },
      phaseZero: RUN_CLIP_POLICY.phaseZero,
      playback: { ...RUN_CLIP_POLICY.playback },
      restVsCalibrationM: r6(restVs),
      bakeTravelSpeedMps: Math.hypot(...m.removedTravelM) > 0 ? r6(Math.hypot(...m.removedTravelM) / a.cycleS) : null,
      playerLegScale: r6((CAL.lengths.thigh + CAL.lengths.shin) / a.restLegM),
      ...a,
    };
    return { rec, isWalk };
  });
  return {
    note: 'Generated by npm run intake-clips (scripts/model/clip-intake.ts). Derived values come from the samples; policy values are chosen (src/sim/run-clip.ts RUN_CLIP_POLICY). Phases are normalized over the closed cycle; phase 0 = left touchdown; stance intervals are half-open [touchdown, liftoff).',
    convention: { units: 'm', up: '+Y', forward: '+Z', anatomicalLeft: '+X', rotations: 'world rotation from bind, quaternion x y z w', source: 'models/scripts/blender/bake_clip.py' },
    policy: RUN_CLIP_POLICY,
    calibrationSha256: CAL.asset.sha256,
    clips: clips.filter((c) => !c.isWalk).map((c) => c.rec).sort((a, b) => a.nominalSpeedMps - b.nominalSpeedMps),
    walk: clips.find((c) => c.isWalk)!.rec, // (exactly one: checked above)
  };
}
