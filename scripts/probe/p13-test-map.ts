// Plan 13b: the test map. Reads the baseline and the consolidated vitest JSON reports and tests/test-map.json, and
// checks that every baseline test maps to a test that exists in the new report and passed. Writes the expanded map
// (baseline title -> new title) as a markdown table. Exit 1 on any unmapped baseline title, any rule that maps to an
// unknown title, any rule that matches nothing, or a mapped test that did not pass.
// Usage: vite-node scripts/probe/p13-test-map.ts <baseline.json> <new.json> <map.json> [out.md]
//
// A test is named `<file> > <describe> > … > <title>` with the file's basename (`harness.test.ts > plan 13a: … > …`).
// The map is an ordered list of rules `{ "from": <regex>, "to": <new name> }`; the first rule whose `from` matches the
// whole baseline name wins. `to` may use `$1`-style groups from `from`.
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';

interface Report {
  testResults: { name: string; assertionResults: { ancestorTitles: string[]; title: string; status: string }[] }[];
}
interface Rule {
  from: string;
  to: string;
}

// `--only <regex>` checks part of the map: only baseline tests whose file basename matches (a group's own files, with a
// new report of that group's files only).
const argv = process.argv.slice(2);
const oi = argv.indexOf('--only');
const only = oi >= 0 ? new RegExp(argv.splice(oi, 2)[1]!) : null;
const [basePath, newPath, mapPath, outPath] = argv;
if (!basePath || !newPath || !mapPath) {
  console.error('usage: p13-test-map.ts <baseline.json> <new.json> <map.json> [out.md] [--only <file regex>]');
  process.exit(2);
}
const names = (r: Report, filter: RegExp | null = null): Map<string, string> => {
  const out = new Map<string, string>();
  for (const f of r.testResults) {
    if (filter && !filter.test(basename(f.name))) continue;
    for (const a of f.assertionResults) out.set([basename(f.name), ...a.ancestorTitles, a.title].join(' > '), a.status);
  }
  return out;
};
const base = names(JSON.parse(readFileSync(basePath, 'utf8')) as Report, only);
const now = names(JSON.parse(readFileSync(newPath, 'utf8')) as Report);
const rules = (JSON.parse(readFileSync(mapPath, 'utf8')) as Rule[]).map((r) => ({ ...r, re: new RegExp(`^(?:${r.from})$`), hits: 0 }));

const problems: string[] = [];
const rows: [string, string][] = [];
for (const name of base.keys()) {
  const rule = rules.find((r) => r.re.test(name));
  if (!rule) {
    problems.push(`unmapped: ${name}`);
    continue;
  }
  rule.hits++;
  const to = name.replace(rule.re, rule.to);
  const st = now.get(to);
  if (st === undefined) problems.push(`unknown target: ${name} -> ${to}`);
  else if (st !== 'passed') problems.push(`target ${st}: ${to}`);
  rows.push([name, to]);
}
for (const r of rules) if (!r.hits) problems.push(`rule matches nothing: ${r.from}`);
const targets = new Set(rows.map(([, to]) => to));
const fresh = [...now.keys()].filter((n) => !targets.has(n));

const md = [
  `# Plan 13b test map`,
  '',
  `Generated by \`scripts/probe/p13-test-map.ts\`: ${base.size} baseline tests, ${now.size} tests now (${fresh.length} of them hold no baseline assertion: new tests).`,
  '',
  '| Baseline test | Now held by |',
  '| --- | --- |',
  ...rows.map(([a, b]) => `| ${a.replace(/\|/g, '\\|')} | ${b.replace(/\|/g, '\\|')} |`),
  '',
  '## Tests with no baseline counterpart',
  '',
  ...fresh.map((n) => `- ${n}`),
  '',
].join('\n');
if (outPath) writeFileSync(outPath, md);
console.log(`baseline ${base.size}, now ${now.size}, mapped ${rows.length}, new ${fresh.length}, problems ${problems.length}`);
for (const p of problems.slice(0, 60)) console.log(`  ${p}`);
if (problems.length > 60) console.log(`  … ${problems.length - 60} more`);
process.exit(problems.length ? 1 : 0);
